-- =====================================================
-- TABLA: REGION
-- =====================================================

CREATE TABLE REGION (
    id_region NUMBER(2)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 7 INCREMENT BY 2),
    nombre_region VARCHAR2(25),

    CONSTRAINT REGION_PK PRIMARY KEY (id_region)
);


-- =====================================================
-- TABLA: GENERO
-- =====================================================

CREATE TABLE GENERO (
    id_genero VARCHAR2(3),
    descripcion_genero VARCHAR2(25),

    CONSTRAINT GENERO_PK PRIMARY KEY (id_genero)
);


-- =====================================================
-- TABLA: ESTADO_CIVIL
-- =====================================================

CREATE TABLE ESTADO_CIVIL (
    id_estado_civil VARCHAR2(2),
    descripcion_estado_civil VARCHAR2(25),

    CONSTRAINT ESTADO_CIVIL_PK PRIMARY KEY (id_estado_civil)
);


-- =====================================================
-- TABLA: IDIOMA
-- =====================================================

CREATE TABLE IDIOMA (
    id_idioma NUMBER(3)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 25 INCREMENT BY 3),
    nombre_idioma VARCHAR2(30),

    CONSTRAINT IDIOMA_PK PRIMARY KEY (id_idioma)
);


-- =====================================================
-- TABLA: TITULO
-- =====================================================

CREATE TABLE TITULO (
    id_titulo VARCHAR2(3),
    descripcion_titulo VARCHAR2(60),

    CONSTRAINT TITULO_PK PRIMARY KEY (id_titulo)
);


-- =====================================================
-- TABLA: COMUNA
-- =====================================================

CREATE TABLE COMUNA (
    id_comuna NUMBER(5),
    comuna_nombre VARCHAR2(25),
    cod_region NUMBER(2),

    CONSTRAINT COMUNA_PK
        PRIMARY KEY (id_comuna, cod_region),

    CONSTRAINT COMUNA_FK_REGION
        FOREIGN KEY (cod_region)
        REFERENCES REGION (id_region)
);


-- =====================================================
-- TABLA: COMPANIA
-- =====================================================

CREATE TABLE COMPANIA (
    id_empresa NUMBER(2),
    nombre_empresa VARCHAR2(25),
    calle VARCHAR2(50),
    numeracion NUMBER(5),
    renta_promedio NUMBER(10),
    pct_aumento NUMBER(4,3),
    cod_comuna NUMBER(5),
    cod_region NUMBER(2),

    CONSTRAINT COMPANIA_PK
        PRIMARY KEY (id_empresa),

    CONSTRAINT COMPANIA_UN_NOMBRE
        UNIQUE (nombre_empresa),

    CONSTRAINT COMPANIA_FK_COMUNA
        FOREIGN KEY (cod_comuna, cod_region)
        REFERENCES COMUNA (id_comuna, cod_region)
);


-- =====================================================
-- TABLA: PERSONAL
-- =====================================================

CREATE TABLE PERSONAL (
    rut_persona NUMBER(8),
    dv_persona CHAR(1),
    primer_nombre VARCHAR2(25),
    segundo_nombre VARCHAR2(25),
    primer_apellido VARCHAR2(25),
    segundo_apellido VARCHAR2(25),
    fecha_contratacion DATE,
    fecha_nacimiento DATE,
    email VARCHAR2(100),
    calle VARCHAR2(50),
    numeracion NUMBER(5),
    sueldo NUMBER(10),
    cod_comuna NUMBER(5),
    cod_region NUMBER(2),
    cod_genero VARCHAR2(3),
    cod_estado_civil VARCHAR2(2),
    cod_empresa NUMBER(2),
    encargado_rut NUMBER(8),

    CONSTRAINT PERSONAL_PK
        PRIMARY KEY (rut_persona),

    CONSTRAINT PERSONAL_FK_COMPANIA
        FOREIGN KEY (cod_empresa)
        REFERENCES COMPANIA (id_empresa),

    CONSTRAINT PERSONAL_FK_COMUNA
        FOREIGN KEY (cod_comuna, cod_region)
        REFERENCES COMUNA (id_comuna, cod_region),

    CONSTRAINT PERSONAL_FK_ESTADO_CIVIL
        FOREIGN KEY (cod_estado_civil)
        REFERENCES ESTADO_CIVIL (id_estado_civil),

    CONSTRAINT PERSONAL_FK_GENERO
        FOREIGN KEY (cod_genero)
        REFERENCES GENERO (id_genero)
);


-- =====================================================
-- FK PERSONAL -> PERSONAL
-- =====================================================

ALTER TABLE PERSONAL
ADD CONSTRAINT PERSONAL_FK_PERSONAL_FK
FOREIGN KEY (encargado_rut)
REFERENCES PERSONAL (rut_persona);


-- =====================================================
-- TABLA: TITULACION
-- =====================================================

CREATE TABLE TITULACION (
    cod_titulo VARCHAR2(3),
    persona_rut NUMBER(8),
    fecha_titulacion DATE,

    CONSTRAINT TITULACION_PK
        PRIMARY KEY (cod_titulo, persona_rut),

    CONSTRAINT TITULACION_FK_PERSONAL
        FOREIGN KEY (persona_rut)
        REFERENCES PERSONAL (rut_persona),

    CONSTRAINT TITULACION_FK_TITULO
        FOREIGN KEY (cod_titulo)
        REFERENCES TITULO (id_titulo)
);


-- =====================================================
-- TABLA: DOMINIO
-- =====================================================

CREATE TABLE DOMINIO (
    id_idioma NUMBER(3),
    persona_rut NUMBER(8),
    nivel VARCHAR2(25),

    CONSTRAINT DOMINIO_PK
        PRIMARY KEY (id_idioma, persona_rut),

    CONSTRAINT DOMINIO_FK_IDIOMA
        FOREIGN KEY (id_idioma)
        REFERENCES IDIOMA (id_idioma),

    CONSTRAINT DOMINIO_FK_PERSONAL
        FOREIGN KEY (persona_rut)
        REFERENCES PERSONAL (rut_persona)
);


