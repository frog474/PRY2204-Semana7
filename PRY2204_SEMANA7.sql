-- =====================================================
-- CASO 4: REPORTE 1
-- =====================================================
-- Muestra todas las compañías con:
-- Nombre de empresa
-- Dirección completa
-- Renta promedio
-- Simulación de renta aplicando el porcentaje de aumento
-- =====================================================

SELECT
    nombre_empresa AS "Nombre Empresa",
    calle || ' ' || numeracion AS "Dirección",
    renta_promedio AS "Renta Promedio",
    renta_promedio * (1 + pct_aumento) AS "Simulación de Renta"
FROM COMPANIA
ORDER BY
    renta_promedio DESC,
    nombre_empresa ASC;


-- =====================================================
-- CASO 4: REPORTE 2
-- =====================================================
-- Muestra:
-- Código de empresa
-- Nombre de empresa
-- Renta promedio actual
-- Porcentaje aumentado en 15%
-- Monto de renta aumentada
-- =====================================================

SELECT
    id_empresa AS "CODIGO",
    nombre_empresa AS "EMPRESA",
    renta_promedio AS "PROM RENTA ACTUAL",
    pct_aumento + 0.15 AS "PCT AUMENTADO EN 15%",
    renta_promedio * (pct_aumento + 0.15) AS "RENTA AUMENTADA"
FROM COMPANIA
ORDER BY
    renta_promedio ASC,
    nombre_empresa DESC;